# Module A — Step 3: Glossary Extraction
# ---------------------------------------------------------------------------

def _extract_noun_phrases_spacy(text: str) -> list[str]:
    doc = _nlp(text[:100_000])  # spaCy limit guard
    phrases = []
    for chunk in doc.noun_chunks:
        phrase = chunk.text.strip().lower()
        # Keep multi-word or capitalised single-word phrases (likely terms)
        if len(phrase.split()) > 1 or chunk.text[0].isupper():
            phrases.append(phrase)
    return phrases


def _extract_noun_phrases_regex(text: str) -> list[str]:
    """
    Fallback: extract capitalised multi-word sequences as candidate terms.
    E.g. "Transformer Architecture", "Retrieval-Augmented Generation"
    """
    pattern = re.compile(r"\b([A-Z][a-z]+(?:[\s\-][A-Z][a-z]+)+)\b")
    return [m.group(0).lower() for m in pattern.finditer(text)]


def _build_definition(term: str, sentences: list[str]) -> str:
    """
    Find the sentence that best contextualises the term and return a
    truncated, cleaned version as the definition.
    """
    term_lower = term.lower()
    # Prefer sentences that contain the term
    candidates = [
        s for s in sentences
        if term_lower in s.lower() and len(s) > 50
    ]
    if not candidates:
        return ""
    # Shortest match is usually the most focused definition sentence
    best = min(candidates, key=len)
    # Trim to ~120 chars for readability
    return best[:180].rstrip(",;") + ("…" if len(best) > 180 else "")


def extract_glossary(
    body_text: str,
    n: int = MAX_GLOSSARY_TERMS,
) -> dict[str, str]:
    """
    Build a glossary of domain terms extracted *from the document itself*.
    Definitions are sentences taken verbatim from the source text.
    No hallucination possible — every definition is a document substring.
    """
    sentences = _split_sentences(body_text)
    if not sentences:
        return {}

    if _SPACY_OK:
        phrases = _extract_noun_phrases_spacy(body_text)
    else:
        phrases = _extract_noun_phrases_regex(body_text)

    if not phrases:
        return {}

    # Count frequency, keep most frequent unique terms
    freq = Counter(p.strip() for p in phrases if 2 <= len(p) <= 60)
    top_terms = [term for term, _ in freq.most_common(n * 3)]

    glossary: dict[str, str] = {}
    for term in top_terms:
        if len(glossary) >= n:
            break
        defn = _build_definition(term, sentences)
        if defn:
            # Title-case the term for display
            display_term = term.title()
            glossary[display_term] = defn

    return glossary


