def _split_sentences(text: str) -> list[str]:
    """Minimal sentence splitter — no NLTK dependency."""
    raw = re.split(r"(?<=[.!?])\s+", text)
    return [s.strip() for s in raw if len(s.strip()) > 40]


def _tfidf_score(sentences: list[str]) -> list[tuple[float, str]]:
    """
    Score sentences by average TF-IDF weight of their tokens.
    Grounded entirely in the document's own vocabulary.
    """
    if not sentences:
        return []

    # Build vocabulary
    stop_words = {
        "the","a","an","and","or","but","in","on","at","to","for","of",
        "with","is","are","was","were","be","been","being","have","has",
        "had","do","does","did","will","would","could","should","may",
        "might","shall","can","not","this","that","these","those","it",
        "its","by","as","from","if","then","than","so","into","about",
        "also","which","who","what","when","where","how","all","each",
        "both","more","most","other","such","only","just","any","there",
    }

    def tokenize(s: str) -> list[str]:
        return [
            w.lower() for w in re.findall(r"\b[a-zA-Z]{3,}\b", s)
            if w.lower() not in stop_words
        ]

    n = len(sentences)
    # TF per sentence
    tf_list = [Counter(tokenize(s)) for s in sentences]
    # DF across all sentences
    df: Counter = Counter()
    for tf in tf_list:
        df.update(tf.keys())

    scored: list[tuple[float, str]] = []
    for idx, (tf, sent) in enumerate(zip(tf_list, sentences)):
        if not tf:
            scored.append((0.0, sent))
            continue
        score = sum(
            count * math.log((n + 1) / (df[word] + 1))
            for word, count in tf.items()
        )
        # Small positional bonus for earlier sentences (intro/abstract)
        position_bonus = 1.0 + max(0.0, 0.3 * (1 - idx / n))
        scored.append((score * position_bonus, sent))

    return scored


def extract_key_takeaways(body_text: str, n: int = MAX_TAKEAWAYS) -> list[str]:
    """
    Return up to `n` key sentences extracted *directly* from `body_text`.
    No external model or network call — fully deterministic, no hallucination.
    """
    sentences = _split_sentences(body_text)
    if not sentences:
        return []

    scored = _tfidf_score(sentences)
    scored.sort(key=lambda x: x[0], reverse=True)
    top = [s for _, s in scored[:n]]

    # Re-order by original position for readability
    order = {sent: i for i, sent in enumerate(sentences)}
    top.sort(key=lambda s: order.get(s, 0))
    return top


