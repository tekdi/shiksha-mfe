"""
AI Engine — Module A: Intelligent Document Ingestion
=====================================================
Implements the full Module-A pipeline described in DMP_2026.yml:

  1. PDF parsing  → structured JSON (headers, body_text, images, metadata)
  2. Key Takeaways → extractive summarisation from source text (sentence
                     scoring via TF-IDF cosine similarity). No hallucination.
  3. Glossary      → domain-term extraction strictly from source text using
                     noun-phrase frequency heuristics + spaCy (if available).
  4. Narration Script → If GROQ_API_KEY is set, generated by Llama 3-8b-8192
                        via Groq Cloud, strictly grounded in the source text.
                        Falls back to a clean extractive script when the key
                        is absent or the call fails.

Design constraints
------------------
* All primary work is done locally (PyMuPDF + scikit-learn + sentence-
  transformers). No external network calls are mandatory.
* The Groq path is an *optional enhancement* — the endpoint always succeeds
  even without a GROQ_API_KEY.
* Text fed to any LLM is always the actual extracted body text, never a
  hallucinated source. System prompts forbid fabrication.
"""

