@app.post("/ingest")
async def ingest_pdf(file: Annotated[UploadFile, File(...)]) -> dict:
    """
    Module A — Full ingestion pipeline.

    1. Validate & stream PDF to disk.
    2. Extract structure via PyMuPDF (headers, body_text, images, metadata).
    3. Extract Key Takeaways (TF-IDF extractive — grounded in source text).
    4. Extract Glossary (noun-phrase frequency — grounded in source text).
    5. Generate Narration Script (extractive or Groq Llama 3 — grounded).

    Returns structured JSON matching the IngestResponse TypeScript interface.
    """
    # ── Validate content-type ──────────────────────────────────────────────
    content_type = (file.content_type or "").split(";")[0].strip().lower()
    if content_type != "application/pdf":
        raise HTTPException(
            status_code=400,
            detail="Unsupported file type. Only PDF files are accepted.",
        )

    temp_path: str | None = None

    try:
        # ── Step 1: Stream to disk ─────────────────────────────────────────
        temp_path = await _read_bounded_to_disk(file, MAX_FILE_SIZE)

        if os.path.getsize(temp_path) == 0:
            raise HTTPException(status_code=400, detail="Empty file uploaded.")

        # ── Step 2: Parse PDF structure ────────────────────────────────────
        with fitz.open(temp_path) as doc:
            if doc.page_count == 0:
                raise HTTPException(status_code=400, detail="PDF has no pages.")

            metadata  = doc.metadata or {}
            headers:         list[str]  = []
            body_text_parts: list[str]  = []
            images:          list[dict] = []

            for page_num in range(doc.page_count):
                page   = doc.load_page(page_num)
                blocks = page.get_text("dict").get("blocks", [])

                for b in blocks:
                    if b.get("type") != 0:
                        continue
                    for line in b.get("lines", []):
                        for span in line.get("spans", []):
                            text = span.get("text", "").strip()
                            if not text:
                                continue
                            font_size = span.get("size", 0)
                            is_bold   = bool(span.get("flags", 0) & 2 ** 4)
                            if font_size > 14 or is_bold:
                                if text not in headers:
                                    headers.append(text)
                            body_text_parts.append(text)

                for img_index, img in enumerate(page.get_images(full=True)):
                    xref       = img[0]
                    base_image = doc.extract_image(xref)
                    image_bytes = base_image.get("image")
                    if image_bytes:
                        images.append({
                            "page":  page_num + 1,
                            "index": img_index,
                            "ext":   base_image.get("ext"),
                            "data":  base64.b64encode(image_bytes).decode("utf-8"),
                        })

        body_text = " ".join(body_text_parts)

        if not body_text.strip():
            # Scanned / image-only PDF — return structure without AI layers
            return {
                "headers":          headers,
                "body_text":        body_text,
                "images":           images,
                "metadata":         metadata,
                "key_takeaways":    [],
                "glossary":         {},
                "narration_script": "",
                "pipeline_note":    "No extractable text — PDF may be image-only.",
            }

        # ── Step 3: Key Takeaways (extractive) ────────────────────────────
        logger.info("Extracting key takeaways…")
        key_takeaways = extract_key_takeaways(body_text)

        # ── Step 4: Glossary (extractive) ──────────────────────────────────
        logger.info("Extracting glossary…")
        glossary = extract_glossary(body_text)

        # ── Step 5: Narration Script (LLM or extractive fallback) ──────────
        logger.info("Generating narration script…")
        narration_script = generate_narration_script(
            body_text, key_takeaways, headers
        )

        logger.info(
            "Ingestion complete — takeaways=%d, glossary=%d, script=%d chars.",
            len(key_takeaways), len(glossary), len(narration_script),
        )

        return {
            "headers":          headers,
            "body_text":        body_text,
            "images":           images,
            "metadata":         metadata,
            "key_takeaways":    key_takeaways,
            "glossary":         glossary,
            "narration_script": narration_script,
        }

    except (fitz.FileDataError, fitz.EmptyFileError):
        logger.error("PyMuPDF failed — corrupted or invalid PDF.")
        raise HTTPException(
            status_code=400,
            detail="Failed to parse PDF. Ensure the file is a valid, non-encrypted PDF.",
        )
    finally:
        if temp_path and os.path.exists(temp_path):
            os.unlink(temp_path)
