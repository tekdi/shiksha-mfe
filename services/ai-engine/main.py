# Module A — Step 4: Narration Script
# ---------------------------------------------------------------------------

_NARRATION_SYSTEM_PROMPT = """\
You are an educational narration writer for an e-learning platform.
Your ONLY job is to write a professional narration script for a slide-deck
or lesson based on the document text provided by the user.

STRICT RULES — you must follow these without exception:
1. Use ONLY the information present in the provided document text.
2. Do NOT invent facts, statistics, names, or concepts not in the text.
3. Do NOT add personal opinions, external knowledge, or assumptions.
4. Write in a clear, friendly, second-person teacher voice ("In this section…").
5. Structure: short intro → main points (drawn from document) → brief close.
6. Output plain text only — no markdown, no bullet points, no headers.
7. Keep the script under 300 words.
"""


def _build_narration_extractive(
    key_takeaways: list[str],
    headers: list[str],
) -> str:
    """
    Pure-extractive fallback narration script — no LLM, no hallucination.
    Constructed entirely from document sentences already extracted.
    """
    lines: list[str] = []

    if headers:
        topic = headers[0]
        lines.append(f"Welcome. In this lesson we will explore: {topic}.")
    else:
        lines.append("Welcome to this lesson.")

    if key_takeaways:
        lines.append("Here are the key points from this document:")
        for i, point in enumerate(key_takeaways[:5], 1):
            lines.append(f"{i}. {point}")

    lines.append(
        "That concludes the core content. "
        "Review the glossary for definitions of key terms."
    )
    return " ".join(lines)


def generate_narration_script(
    body_text: str,
    key_takeaways: list[str],
    headers: list[str],
) -> str:
    """
    Generate a narration script.
    * If GROQ_API_KEY is set: call Llama 3 via Groq Cloud with strict
      grounding system prompt and the real document text as context.
    * Otherwise: fall back to extractive script (no hallucination).
    """
    # Extractive fallback always works
    fallback = _build_narration_extractive(key_takeaways, headers)

    if not GROQ_API_KEY or not _GROQ_SDK_OK:
        logger.info("Narration: using extractive fallback (no GROQ_API_KEY).")
        return fallback

    # Trim body text to context window
    context_text = body_text[:LLM_CONTEXT_CHARS]
    user_message = (
        "Write a narration script for the following document.\n\n"
        f"--- DOCUMENT TEXT START ---\n{context_text}\n--- DOCUMENT TEXT END ---"
    )

    try:
        client = GroqClient(api_key=GROQ_API_KEY)
        response = client.chat.completions.create(
            model=GROQ_MODEL,
            messages=[
                {"role": "system", "content": _NARRATION_SYSTEM_PROMPT},
                {"role": "user",   "content": user_message},
            ],
            max_tokens=LLM_MAX_TOKENS,
            temperature=0.3,   # Low temperature → more faithful to source
        )
        script = response.choices[0].message.content.strip()
        logger.info("Narration: Groq LLM script generated (%d chars).", len(script))
        return script
    except Exception as exc:
        logger.warning("Narration: Groq call failed (%s) — using extractive fallback.", exc)
        return fallback


